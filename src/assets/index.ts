import { Glob } from "bun";
import { dirname, extname, join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";

const extensions = ["svg", "png", "jpg", "jpeg", "gif", "webp", "avif"];

/** `icons/arrow-left.svg` -> `iconsArrowLeft`, valid as an identifier. */
function exportName(file: string) {
  const words = file
    .slice(0, -extname(file).length)
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean);
  const name = words
    .map((w, i) => (i == 0 ? w[0]!.toLowerCase() : w[0]!.toUpperCase()) + w.slice(1))
    .join("");
  return /^[0-9]/.test(name) ? `_${name}` : name || "_";
}

/**
 * `assets [dir] [--out file]`: write a barrel exporting the url of every image
 * under `dir` (default `assets`), so documents can
 * `import { logo } from "@assets"`. Rerun it after adding or renaming images.
 */
export async function assets(args: string[]) {
  const { positionals, values } = parseArgs({
    args,
    options: { out: { type: "string" } },
    allowPositionals: true,
  });
  if (positionals.length > 1) throw new Error("Usage: zefpdf-lab assets [dir] [--out file]");

  const dir = resolve(positionals[0] ?? "assets");
  const out = resolve(values.out ?? join(dir, "index.tsx"));
  const glob = new Glob(`**/*.{${extensions.join(",")}}`);
  const files = (await Array.fromAsync(glob.scan({ cwd: dir }))).sort();

  // Two files mapping to one name (logo.svg, logo.png) both get their extension.
  const names = files.map(exportName);
  const lines = files.map((file, i) => {
    const clash = names.indexOf(names[i]!) != names.lastIndexOf(names[i]!);
    const name = clash ? names[i] + extname(file).slice(1).toUpperCase() : names[i];
    const path = "./" + relative(dirname(out), join(dir, file)).split("\\").join("/");
    return `export { default as ${name} } from ${JSON.stringify(path)};`;
  });

  const header = "// Generated by `zefpdf-lab assets`: rerun it instead of editing.\n";
  await Bun.write(out, header + lines.join("\n") + "\n");
  console.log(`Wrote ${files.length} exports to ${relative(process.cwd(), out)}`);
}
